// Embeds users/USER_PROFILE.md, PREFERENCES.md and WORKING_STYLE.md into
// src/alfred/cognitive/context/user-profile.generated.ts as string constants.
//
//   npm run generate:user-profile          # rewrite the module if stale
//   npm run generate:user-profile -- --check   # exit 1 if it is stale
//
// Why a generated module: the Cloud Functions bundle may not read files at
// runtime (users/ is not uploaded), yet production's system prompt must be
// rendered from users/*.md. A plain .ts module typechecks in src/, loads in
// vitest and tsx, and is inlined by esbuild without a custom loader.
//
// The module is committed. tests/unit/user-profile-sources.test.ts fails when
// it no longer matches users/*.md, and functions/build.js regenerates it
// before bundling, so a deploy always ships the current files.
//
// Plain ESM (no TypeScript) so functions/build.js can import it with node.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

export const USER_PROFILE_GENERATED_PATH = join(
  repoRoot, "src", "alfred", "cognitive", "context", "user-profile.generated.ts"
);

const FILES = [
  ["userProfile", "USER_PROFILE.md"],
  ["preferences", "PREFERENCES.md"],
  ["workingStyle", "WORKING_STYLE.md"]
];

/** Returns the TypeScript source of the generated module for the current users/*.md. */
export function renderUserProfileSourcesModule(root = repoRoot) {
  const entries = FILES.map(([key, file]) => {
    const text = readFileSync(join(root, "users", file), "utf8");
    return `  /** users/${file} */\n  ${key}: ${JSON.stringify(text)}`;
  });
  return [
    "// GENERATED by scripts/generate-user-profile-sources.mjs from users/*.md. Do not edit.",
    "// Regenerate with `npm run generate:user-profile` after editing users/*.md.",
    'import type { UserProfileSources } from "./user-profile.types.js";',
    "",
    "/** users/*.md as committed, embedded so the functions bundle never reads files. */",
    "export const USER_PROFILE_SOURCES: UserProfileSources = {",
    entries.join(",\n"),
    "};",
    ""
  ].join("\n");
}

function readOrEmpty(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

/**
 * Rewrites the generated module when it differs from users/*.md.
 * Returns true when the file was (or, with check=true, would be) changed.
 */
export function syncUserProfileSourcesModule({ check = false } = {}) {
  const next = renderUserProfileSourcesModule();
  const stale = readOrEmpty(USER_PROFILE_GENERATED_PATH) !== next;
  if (stale && !check) writeFileSync(USER_PROFILE_GENERATED_PATH, next);
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const stale = syncUserProfileSourcesModule({ check });
  if (check && stale) {
    console.error("user-profile.generated.ts is out of date with users/*.md; run `npm run generate:user-profile`.");
    process.exit(1);
  }
  console.log(stale ? "user-profile.generated.ts updated from users/*.md." : "user-profile.generated.ts is up to date.");
}
