use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct SetupConfig {
    pub project_id: String,
    pub allowed_email: String,
    pub allowed_uid: String,
    pub groq_api_key: String,
    pub gemini_api_key: String,
    pub tavily_api_key: String,
    pub evren_api_key: Option<String>,
    pub ollama_url: Option<String>,
    pub firestore_region: Option<String>,
    pub billing_account_id: Option<String>,
    /// The owner's name as Alfred should address them; empty keeps the example profile's defaults.
    #[serde(default)]
    pub owner_name: String,
}

/// Shell quoting helper following POSIX escaping rules.
/// Wraps any string in single quotes and safely escapes existing single quotes.
pub fn shell_quote(s: &str) -> String {
    let escaped = s.replace('\'', r"'\''");
    format!("'{}'", escaped)
}

/// Generates the standard root `.env` file content from the SetupConfig.
pub fn generate_env_file(config: &SetupConfig) -> String {
    let mut out = String::new();
    out.push_str("# ==============================================================================\n");
    out.push_str("# Alfred — Generated by Setup-UI (Rust WebAssembly Core)\n");
    out.push_str("# ==============================================================================\n\n");

    out.push_str("# --- Single-User Authorization ---------------------------------------------------\n");
    out.push_str(&format!("ALLOWED_EMAIL={}\n", shell_quote(&config.allowed_email)));
    if config.allowed_uid.trim().is_empty() {
        out.push_str("ALLOWED_UID=''\n# Note: ALLOWED_UID is empty and will be authorized via verified email.\n\n");
    } else {
        out.push_str(&format!("ALLOWED_UID={}\n\n", shell_quote(config.allowed_uid.trim())));
    }

    out.push_str("# --- Model Providers ------------------------------------------------------------\n");
    out.push_str("ALFRED_LLM_PROVIDER='groq'\n");
    out.push_str(&format!("GROQ_API_KEY={}\n", shell_quote(&config.groq_api_key)));
    out.push_str("GROQ_MODEL='openai/gpt-oss-120b'\n");
    out.push_str(&format!("GEMINI_API_KEY={}\n", shell_quote(&config.gemini_api_key)));
    out.push_str("EMBEDDING_PROVIDER='gemini'\n");
    out.push_str("EMBEDDING_MODEL='gemini-embedding-001'\n");
    out.push_str("EMBEDDING_DIMENSION=768\n\n");

    out.push_str("# --- Fact-Checked Web Search ----------------------------------------------------\n");
    out.push_str(&format!("TAVILY_API_KEY={}\n\n", shell_quote(&config.tavily_api_key)));

    if let Some(ref evren) = config.evren_api_key {
        if !evren.trim().is_empty() {
            out.push_str("# --- Optional Turkish National LLM (TÜBİTAK BİLGEM) ----------------------------\n");
            out.push_str(&format!("EVREN_API_KEY={}\n", shell_quote(evren.trim())));
            out.push_str("EVREN_MODEL='qwen3.8-flash-next'\n\n");
        }
    }

    let ollama_url = config.ollama_url.as_deref().unwrap_or("http://localhost:11434");
    out.push_str("# --- Optional Local Ollama Fallback ---------------------------------------------\n");
    out.push_str(&format!("OLLAMA_BASE_URL={}\n", shell_quote(ollama_url)));
    out.push_str("OLLAMA_MODEL='gemma4:12b'\n");

    out
}

/// Generates an idempotent, injection-safe, secret-free Google Cloud Shell provisioning script.
/// API keys are NOT hardcoded into the script text; they are retrieved from environment variables
/// or prompted interactively if not set.
pub fn generate_cloud_shell_script(config: &SetupConfig) -> String {
    let mut script = String::new();
    script.push_str("#!/usr/bin/env bash\n");
    script.push_str("set -euo pipefail\n\n");

    script.push_str("# ==============================================================================\n");
    script.push_str("# Alfred — Automated Google Cloud Shell Provisioning Script\n");
    script.push_str(&format!("# Target Project: {}\n", config.project_id.trim()));
    script.push_str("# ==============================================================================\n\n");

    script.push_str(&format!("PROJECT_ID={}\n", shell_quote(config.project_id.trim())));
    let region = config.firestore_region.as_deref().unwrap_or("europe-west1");
    let safe_region = if region.trim().is_empty() { "europe-west1" } else { region.trim() };
    script.push_str(&format!("FIRESTORE_REGION={}\n\n", shell_quote(safe_region)));

    script.push_str("# Helper to safely back up existing configuration files before overwriting\n");
    script.push_str("backup_if_exists() {\n");
    script.push_str("  local target_file=\"$1\"\n");
    script.push_str("  if [ -f \"$target_file\" ]; then\n");
    script.push_str("    local ts\n");
    script.push_str("    ts=$(date +%Y%m%d%H%M%S)\n");
    script.push_str("    echo \"  Backing up $target_file -> ${target_file}.backup-${ts}\"\n");
    script.push_str("    cp \"$target_file\" \"${target_file}.backup-${ts}\"\n");
    script.push_str("  fi\n");
    script.push_str("}\n\n");

    script.push_str("# 1. Google Cloud Project Setup (Auto-creates if project does not exist)\n");
    script.push_str("if ! gcloud projects describe \"$PROJECT_ID\" >/dev/null 2>&1; then\n");
    script.push_str("  echo \"🚀 [Alfred Setup] Project $PROJECT_ID does not exist yet. Creating it in Google Cloud...\"\n");
    script.push_str("  gcloud projects create \"$PROJECT_ID\" --name=\"Alfred Butler\"\n");
    script.push_str("fi\n\n");

    script.push_str("echo \"🦇 [Alfred Setup] Configuring Google Cloud project...\"\n");
    script.push_str("gcloud config set project \"$PROJECT_ID\"\n\n");

    script.push_str("# 2. Billing Account Association\n");
    script.push_str("billing_enabled() {\n");
    script.push_str("  [ \"$(gcloud billing projects describe \"$PROJECT_ID\" --format=\"value(billingEnabled)\" 2>/dev/null)\" = \"True\" ]\n");
    script.push_str("}\n");
    match config.billing_account_id.as_deref().map(str::trim).filter(|id| !id.is_empty()) {
        Some(ba_id) => script.push_str(&billing_link_snippet(ba_id)),
        None => script.push_str(generate_billing_autolink_snippet()),
    }
    script.push_str(BILLING_REQUIRED_CHECK);

    script.push_str("echo \"🔑 [Alfred Setup] Enabling required Google Cloud and Firebase APIs...\"\n");
    script.push_str("gcloud services enable \\\n");
    script.push_str("  secretmanager.googleapis.com \\\n");
    script.push_str("  cloudfunctions.googleapis.com \\\n");
    script.push_str("  run.googleapis.com \\\n");
    script.push_str("  cloudbuild.googleapis.com \\\n");
    script.push_str("  firestore.googleapis.com \\\n");
    script.push_str("  firebase.googleapis.com \\\n");
    script.push_str("  identitytoolkit.googleapis.com\n\n");

    script.push_str("echo \"🔥 [Alfred Setup] Ensuring Firebase is enabled on Google Cloud project...\"\n");
    script.push_str("npx --yes firebase-tools projects:addfirebase \"$PROJECT_ID\" >/dev/null 2>&1 || true\n\n");

    script.push_str("echo \"🗄️ [Alfred Setup] Ensuring Firestore database exists in Native mode...\"\n");
    script.push_str("if ! gcloud firestore databases list --format=\"value(name)\" 2>/dev/null | grep -q \"(default)\"; then\n");
    script.push_str("  echo \"  Creating Firestore (default) database in $FIRESTORE_REGION...\"\n");
    script.push_str("  gcloud firestore databases create --location=\"$FIRESTORE_REGION\" --type=firestore-native >/dev/null 2>&1 || true\n");
    script.push_str("else\n");
    script.push_str("  echo \"  Firestore (default) database already exists; skipping.\"\n");
    script.push_str("fi\n\n");

    script.push_str("echo \"📱 [Alfred Setup] Configuring Firebase Web App...\"\n");
    script.push_str("WEB_APP_ID=$(npx --yes firebase-tools apps:list WEB --project=\"$PROJECT_ID\" 2>/dev/null | grep -oE \"1:[0-9]+:web:[a-f0-9]+\" | head -n 1 || true)\n");
    script.push_str("if [ -z \"$WEB_APP_ID\" ]; then\n");
    script.push_str("  echo \"  Registering new Firebase Web App (Alfred Web)...\"\n");
    script.push_str("  npx --yes firebase-tools apps:create WEB \"Alfred Web\" --project=\"$PROJECT_ID\" >/dev/null 2>&1 || true\n");
    script.push_str("else\n");
    script.push_str("  echo \"  Firebase Web App already exists ($WEB_APP_ID).\"\n");
    script.push_str("fi\n\n");

    script.push_str("echo \"  Resolving Firebase Web SDK configuration...\"\n");
    script.push_str("npx --yes firebase-tools apps:sdkconfig WEB --project=\"$PROJECT_ID\" --out=firebase-app-config.json >/dev/null 2>&1 || true\n\n");

    script.push_str("# Helper to create or update secrets in Google Secret Manager\n");
    script.push_str("create_or_update_secret() {\n");
    script.push_str("  local secret_name=\"$1\"\n");
    script.push_str("  local secret_value=\"${2:-}\"\n");
    script.push_str("  if ! gcloud secrets describe \"$secret_name\" >/dev/null 2>&1; then\n");
    script.push_str("    echo \"  Creating secret container: $secret_name...\"\n");
    script.push_str("    gcloud secrets create \"$secret_name\" --replication-policy=automatic\n");
    script.push_str("    local initial_val=\"$secret_value\"\n");
    script.push_str("    if [ -z \"$initial_val\" ]; then\n");
    script.push_str("      initial_val=\"unset\"\n");
    script.push_str("    fi\n");
    script.push_str("    echo \"  Initializing version for: $secret_name...\"\n");
    script.push_str("    printf '%s' \"$initial_val\" | gcloud secrets versions add \"$secret_name\" --data-file=-\n");
    script.push_str("  else\n");
    script.push_str("    if [ -n \"$secret_value\" ] && [ \"$secret_value\" != \"unset\" ]; then\n");
    script.push_str("      echo \"  Updating secret with user-provided key: $secret_name...\"\n");
    script.push_str("      printf '%s' \"$secret_value\" | gcloud secrets versions add \"$secret_name\" --data-file=-\n");
    script.push_str("    else\n");
    script.push_str("      echo \"  Secret $secret_name already exists; preserving existing secret version.\"\n");
    script.push_str("    fi\n");
    script.push_str("  fi\n");
    script.push_str("}\n\n");

    script.push_str("# Helper to prompt for secret interactively if not provided via environment\n");
    script.push_str("prompt_secret_if_interactive() {\n");
    script.push_str("  local var_name=\"$1\"\n");
    script.push_str("  local prompt_label=\"$2\"\n");
    script.push_str("  local current_val=\"${!var_name:-}\"\n");
    script.push_str("  if [ -z \"$current_val\" ] && [ -t 0 ]; then\n");
    script.push_str("    echo -n \"🔑 Enter $prompt_label (leave empty to skip): \"\n");
    script.push_str("    read -r -s input_val\n");
    script.push_str("    echo \"\"\n");
    script.push_str("    printf -v \"$var_name\" '%s' \"$input_val\"\n");
    script.push_str("  fi\n");
    script.push_str("}\n\n");

    script.push_str("prompt_secret_if_interactive \"GROQ_API_KEY\" \"Groq API Key\"\n");
    script.push_str("prompt_secret_if_interactive \"GEMINI_API_KEY\" \"Google Gemini API Key\"\n");
    script.push_str("prompt_secret_if_interactive \"TAVILY_API_KEY\" \"Tavily API Key\"\n");
    script.push_str("prompt_secret_if_interactive \"EVREN_API_KEY\" \"TÜBİTAK EVREN API Key\"\n\n");

    script.push_str("echo \"🛡️ [Alfred Setup] Provisioning Secret Manager vault...\"\n");
    script.push_str("create_or_update_secret \"GROQ_API_KEY\" \"${GROQ_API_KEY:-}\"\n");
    script.push_str("create_or_update_secret \"GEMINI_API_KEY\" \"${GEMINI_API_KEY:-}\"\n");
    script.push_str("create_or_update_secret \"TAVILY_API_KEY\" \"${TAVILY_API_KEY:-}\"\n");
    script.push_str("create_or_update_secret \"EVREN_API_KEY\" \"${EVREN_API_KEY:-}\"\n");
    script.push_str("create_or_update_secret \"GOOGLE_OAUTH_CLIENT_ID\" \"${GOOGLE_OAUTH_CLIENT_ID:-}\"\n");
    script.push_str("create_or_update_secret \"GOOGLE_OAUTH_CLIENT_SECRET\" \"${GOOGLE_OAUTH_CLIENT_SECRET:-}\"\n\n");

    script.push_str("echo \"📝 [Alfred Setup] Writing local environment config (.env)...\"\n");
    script.push_str("backup_if_exists \".env\"\n");
    script.push_str("cat << 'ALFRED_ENV_EOF' > .env\n");
    script.push_str("# ==============================================================================\n");
    script.push_str("# Alfred — Generated by Setup-UI (Rust WebAssembly Core)\n");
    script.push_str("# ==============================================================================\n\n");
    script.push_str(&format!("ALLOWED_EMAIL={}\n", shell_quote(&config.allowed_email)));
    if config.allowed_uid.trim().is_empty() {
        script.push_str("ALLOWED_UID=''\n# Note: ALLOWED_UID is empty and will be authorized via verified email.\n\n");
    } else {
        script.push_str(&format!("ALLOWED_UID={}\n\n", shell_quote(config.allowed_uid.trim())));
    }
    script.push_str("ALFRED_LLM_PROVIDER='groq'\n");
    script.push_str("GROQ_MODEL='openai/gpt-oss-120b'\n");
    script.push_str("EMBEDDING_PROVIDER='gemini'\n");
    script.push_str("EMBEDDING_MODEL='gemini-embedding-001'\n");
    script.push_str("EMBEDDING_DIMENSION=768\n\n");
    let ollama_url = config.ollama_url.as_deref().unwrap_or("http://localhost:11434");
    script.push_str(&format!("OLLAMA_BASE_URL={}\n", shell_quote(ollama_url)));
    script.push_str("OLLAMA_MODEL='gemma4:12b'\n");
    script.push_str("ALFRED_ENV_EOF\n\n");

    script.push_str("# Append non-empty environment secrets to root .env if provided\n");
    script.push_str("if [ -n \"${GROQ_API_KEY:-}\" ]; then echo \"GROQ_API_KEY='${GROQ_API_KEY}'\" >> .env; fi\n");
    script.push_str("if [ -n \"${GEMINI_API_KEY:-}\" ]; then echo \"GEMINI_API_KEY='${GEMINI_API_KEY}'\" >> .env; fi\n");
    script.push_str("if [ -n \"${TAVILY_API_KEY:-}\" ]; then echo \"TAVILY_API_KEY='${TAVILY_API_KEY}'\" >> .env; fi\n");
    script.push_str("if [ -n \"${EVREN_API_KEY:-}\" ]; then echo \"EVREN_API_KEY='${EVREN_API_KEY}'\" >> .env; echo \"EVREN_MODEL='qwen3.8-flash-next'\" >> .env; fi\n\n");

    script.push_str("echo \"📝 [Alfred Setup] Writing Cloud Functions environment config (functions/.env.${PROJECT_ID})...\"\n");
    script.push_str("backup_if_exists \"functions/.env.${PROJECT_ID}\"\n");
    script.push_str("cat << 'ALFRED_FUNCTIONS_ENV_EOF' > \"functions/.env.${PROJECT_ID}\"\n");
    script.push_str("# Project-specific non-sensitive runtime configuration for Cloud Functions\n");
    script.push_str(&format!("ALLOWED_EMAIL={}\n", shell_quote(&config.allowed_email)));
    script.push_str(&format!("ALLOWED_UID={}\n", shell_quote(config.allowed_uid.trim())));
    script.push_str("# The web app only starts App Check when NEXT_PUBLIC_RECAPTCHA_SITE_KEY is set,\n");
    script.push_str("# which a fresh install does not have yet; enforcing it would reject every request.\n");
    script.push_str("# Remove this line after setting up App Check (docs/OPERATIONS.md).\n");
    script.push_str("ENFORCE_APP_CHECK=false\n");
    script.push_str("ALFRED_FUNCTIONS_ENV_EOF\n\n");

    script.push_str("echo \"📝 [Alfred Setup] Writing web app production configuration (apps/web/.env.production.local)...\"\n");
    script.push_str("backup_if_exists \"apps/web/.env.production.local\"\n");
    script.push_str("if [ -f \"firebase-app-config.json\" ]; then\n");
    // The values reach node through its environment: quoting them inside the
    // single-quoted program would end that quote (an empty UID became `const allowedUid = ;`).
    script.push_str(&format!(
        "  ALFRED_WEB_ALLOWED_UID={} ALFRED_WEB_ALLOWED_EMAIL={} node -e '\n",
        shell_quote(config.allowed_uid.trim()),
        shell_quote(&config.allowed_email)
    ));
    script.push_str("    const fs = require(\"fs\");\n");
    script.push_str("    try {\n");
    script.push_str("      const cfg = JSON.parse(fs.readFileSync(\"firebase-app-config.json\", \"utf8\"));\n");
    script.push_str("      const allowedUid = process.env.ALFRED_WEB_ALLOWED_UID || \"\";\n");
    script.push_str("      const allowedEmail = process.env.ALFRED_WEB_ALLOWED_EMAIL || \"\";\n");
    script.push_str("      let envContent = \"# Generated by Alfred Cloud Shell Provisioning\\n\";\n");
    script.push_str("      envContent += `NEXT_PUBLIC_FIREBASE_API_KEY=${cfg.apiKey || \"\"}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN=${cfg.authDomain || \"\"}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_FIREBASE_PROJECT_ID=${cfg.projectId || \"\"}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET=${cfg.storageBucket || \"\"}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID=${cfg.messagingSenderId || \"\"}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_FIREBASE_APP_ID=${cfg.appId || \"\"}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_ALLOWED_UID=${allowedUid}\\n`;\n");
    script.push_str("      envContent += `NEXT_PUBLIC_ALLOWED_EMAIL=${allowedEmail}\\n`;\n");
    script.push_str("      fs.writeFileSync(\"apps/web/.env.production.local\", envContent);\n");
    script.push_str("    } catch (e) {\n");
    script.push_str("      console.error(\"Failed to parse firebase-app-config.json:\", e);\n");
    script.push_str("      process.exit(1);\n");
    script.push_str("    }\n");
    script.push_str("  '\n");
    script.push_str("  rm -f firebase-app-config.json\n");
    script.push_str("fi\n\n");

    script.push_str("echo \"📦 [Alfred Setup] Installing dependencies...\"\n");
    script.push_str("npm ci\n");
    script.push_str("npm ci --prefix functions\n\n");

    script.push_str("echo \"🧠 [Alfred Setup] Initializing user persona profile digest...\"\n");
    script.push_str(&profile_init_command(&config.owner_name));

    script.push_str("echo \"🏗️ [Alfred Setup] Building Next.js web application for production...\"\n");
    script.push_str("npm run build:web\n\n");

    script.push_str("if [ ! -f \"apps/web/out/index.html\" ]; then\n");
    script.push_str("  echo \"❌ [Alfred Setup] Web build failed: apps/web/out/index.html not found!\"\n");
    script.push_str("  exit 1\n");
    script.push_str("fi\n\n");

    script.push_str("echo \"🚀 [Alfred Setup] Deploying to Firebase (Hosting, Functions & Security Rules)...\"\n");
    script.push_str("npx --yes firebase-tools use \"$PROJECT_ID\"\n");
    // Hosting uploads 200 files at once by default; from Cloud Shell that has
    // dropped uploads ("Failed to make request ... retries exhausted"), so the
    // script uploads fewer at a time (a caller's value wins) and retries the deploy.
    script.push_str("export FIREBASE_HOSTING_UPLOAD_CONCURRENCY=\"${FIREBASE_HOSTING_UPLOAD_CONCURRENCY:-8}\"\n");
    script.push_str(&format!("for attempt in $(seq 1 {DEPLOY_ATTEMPTS}); do\n"));
    script.push_str("  if npx --yes firebase-tools deploy --only hosting,functions,firestore:rules,firestore:indexes --non-interactive --force; then\n");
    script.push_str("    break\n");
    script.push_str("  fi\n");
    script.push_str(&format!("  if [ \"$attempt\" -eq {DEPLOY_ATTEMPTS} ]; then\n"));
    script.push_str("    echo \"[Alfred Setup] ERROR deploy-failed after $attempt attempts\" >&2\n");
    script.push_str("    exit 1\n");
    script.push_str("  fi\n");
    script.push_str(&format!("  echo \"[Alfred Setup] Deploy attempt $attempt/{DEPLOY_ATTEMPTS} failed; retrying in 15 s...\"\n"));
    script.push_str("  sleep 15\n");
    script.push_str("done\n\n");

    script.push_str("echo \"\"\n");
    script.push_str("echo \"===================================================================\"\n");
    script.push_str("echo \"✨ Alfred has been successfully provisioned and deployed!\"\n");
    script.push_str("echo \"🌐 Open your application: https://${PROJECT_ID}.web.app\"\n");
    script.push_str("echo \"===================================================================\"\n");

    script
}

/// `npm run profile:init` for the owner: the first word becomes the short
/// name Alfred uses, the whole name the full name. Always rewrites `users/`,
/// which ships with an example profile.
fn profile_init_command(owner_name: &str) -> String {
    let full = owner_name.split_whitespace().collect::<Vec<_>>().join(" ");
    match full.split(' ').next().filter(|first| !first.is_empty()) {
        Some(first) => format!(
            "npm run profile:init -- --defaults --name {} --full-name {}\n\n",
            shell_quote(first),
            shell_quote(&full)
        ),
        None => "npm run profile:init -- --defaults\n\n".to_string(),
    }
}

/// Links the chosen billing account, showing gcloud's errors and retrying a
/// few times: a project that was created seconds ago is not always visible to
/// the billing API yet.
fn billing_link_snippet(billing_account_id: &str) -> String {
    let mut s = format!("TARGET_BILLING_ACCOUNT={}\n", shell_quote(billing_account_id));
    s.push_str("if billing_enabled; then\n");
    s.push_str("  echo \"💳 [Alfred Setup] Billing account is already linked to project $PROJECT_ID.\"\n");
    s.push_str("else\n");
    s.push_str("  echo \"💳 [Alfred Setup] Linking selected billing account: $TARGET_BILLING_ACCOUNT...\"\n");
    s.push_str("  for attempt in 1 2 3 4 5; do\n");
    s.push_str("    if link_output=\"$(gcloud billing projects link \"$PROJECT_ID\" --billing-account=\"$TARGET_BILLING_ACCOUNT\" 2>&1)\"; then\n");
    s.push_str("      echo \"$link_output\"\n");
    s.push_str("      break\n");
    s.push_str("    fi\n");
    s.push_str("    echo \"$link_output\"\n");
    s.push_str("    case \"$link_output\" in\n");
    s.push_str("      *\"quota exceeded\"*)\n");
    s.push_str("        echo \"  This billing account already has as many linked projects as its quota allows.\"\n");
    s.push_str("        echo \"  See its projects: gcloud billing projects list --billing-account=$TARGET_BILLING_ACCOUNT\"\n");
    s.push_str("        echo \"  Unlink one you no longer need, or ask for more: https://support.google.com/code/contact/billing_quota_increase\"\n");
    s.push_str(&format!("        echo \"{BILLING_QUOTA_MARKER} $TARGET_BILLING_ACCOUNT\"\n"));
    s.push_str("        exit 3 ;;\n");
    s.push_str("    esac\n");
    s.push_str("    [ \"$attempt\" = 5 ] || { echo \"  Linking failed (attempt $attempt of 5); retrying in 10 s...\"; sleep 10; }\n");
    s.push_str("  done\n");
    s.push_str("fi\n");
    s
}

/// Stops the script with the likely causes when the project still has no
/// billing: every API enabled afterwards would fail with a less clear error.
/// Printed when the billing account has no room for another project; the
/// wizard offers another billing account or Google account. Exit code 3.
/// How many times the script runs `firebase deploy` before giving up.
pub const DEPLOY_ATTEMPTS: u32 = 3;

pub const BILLING_QUOTA_MARKER: &str = "[Alfred Setup] ERROR billing-quota-exceeded";
/// Printed when billing is still off after linking. Exit code 1.
pub const BILLING_DISABLED_MARKER: &str = "[Alfred Setup] ERROR billing-not-enabled";

const BILLING_REQUIRED_CHECK: &str = "if ! billing_enabled; then\n  echo \"❌ [Alfred Setup] Billing is not enabled on project $PROJECT_ID, so its APIs cannot be turned on.\"\n  echo \"   Common causes: the billing account already has as many linked projects as its quota allows\"\n  echo \"   (unlink an old project or request more), or your account may not link projects to it\"\n  echo \"   (it needs the Billing Account User role).\"\n  echo \"   Link it at https://console.cloud.google.com/billing/linkedaccount?project=$PROJECT_ID\"\n  echo \"   and run the setup again with the same project ID; finished steps are skipped.\"\n  echo \"[Alfred Setup] ERROR billing-not-enabled\"\n  exit 1\nfi\n\n";

fn generate_billing_autolink_snippet() -> &'static str {
    "if ! gcloud billing projects describe \"$PROJECT_ID\" --format=\"value(billingAccountName)\" 2>/dev/null | grep -q \"/\"; then\n  echo \"💳 [Alfred Setup] Linking open Google Cloud billing account...\"\n  for ba in $(gcloud billing accounts list --filter=\"open=true\" --format=\"value(ACCOUNT_ID)\" 2>/dev/null); do\n    echo \"  Attempting to link billing account $ba...\"\n    if gcloud billing projects link \"$PROJECT_ID\" --billing-account=\"$ba\" 2>/dev/null; then\n      echo \"  ✓ Successfully linked billing account: $ba\"\n      break\n    fi\n  done\nelse\n  echo \"💳 [Alfred Setup] Billing account is already linked to project $PROJECT_ID.\"\nfi\n\n"
}

