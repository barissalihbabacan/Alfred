// Embeds users/USER_PROFILE.md, PREFERENCES.md and WORKING_STYLE.md, and the
// condensed digest of them that the system prompt actually carries
// (src/alfred/cognitive/context/user-profile.digest.md), into
// src/alfred/cognitive/context/user-profile.generated.ts as string constants.
//
//   npm run generate:user-profile          # rewrite the module if stale
//   npm run generate:user-profile -- --check   # exit 1 if it is stale
//
// Both modes also exit 1 when the digest is stale. The digest records the
// sha256 of each users/*.md file it was written from; a hash that no longer
// matches means nobody has reviewed the digest against the edit. To fix it,
// update the digest text by hand and paste in the hash lines this prints.
//
// Why a generated module: the Cloud Functions bundle may not read files at
// runtime (users/ is not uploaded), yet production's system prompt must be
// rendered from users/*.md. A plain .ts module typechecks in src/, loads in
// vitest and tsx, and is inlined by esbuild without a custom loader.
//
// The module is committed. tests/unit/user-profile-sources.test.ts fails when
// it no longer matches users/*.md, and functions/build.js regenerates it
// before bundling, so a deploy always ships the current files.
//
// Plain ESM (no TypeScript) so functions/build.js can import it with node.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

export const USER_PROFILE_GENERATED_PATH = join(
  repoRoot, "src", "alfred", "cognitive", "context", "user-profile.generated.ts"
);

const FILES = [
  ["userProfile", "USER_PROFILE.md"],
  ["preferences", "PREFERENCES.md"],
  ["workingStyle", "WORKING_STYLE.md"]
];

const DIGEST_RELATIVE_PATH = join("src", "alfred", "cognitive", "context", "user-profile.digest.md");
const DIGEST_HASH_LINE = /^<!--\s*sha256\s+(\S+)\s+([0-9a-f]{64})\s*-->$/;

/**
 * Splits the digest file into its recorded source hashes and its body: the
 * text after the leading `<!-- ... -->` comment lines, trimmed.
 */
export function parseUserProfileDigest(text) {
  const lines = text.replace(/\r\n?/g, "\n").split("\n");
  const hashes = {};
  let i = 0;
  for (; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line.startsWith("<!--")) break;
    const match = DIGEST_HASH_LINE.exec(line);
    if (match) hashes[match[1]] = match[2];
  }
  return { hashes, body: lines.slice(i).join("\n").trim() };
}

const sha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex");
const readDigest = (root) => parseUserProfileDigest(readFileSync(join(root, DIGEST_RELATIVE_PATH), "utf8"));

/**
 * Compares the digest's recorded hashes with users/*.md. Returns one entry per
 * file whose hash is missing or differs; empty when the digest is current.
 */
export function staleUserProfileDigestSources(root = repoRoot) {
  const { hashes } = readDigest(root);
  return FILES.flatMap(([, file]) => {
    const actual = sha256(readFileSync(join(root, "users", file), "utf8"));
    return hashes[file] === actual ? [] : [{ file, recorded: hashes[file] ?? null, actual }];
  });
}

/** Error text for a stale digest, including the hash lines to paste in. */
export function describeStaleUserProfileDigest(stale) {
  return [
    `user-profile.digest.md was written from a different version of ${stale.map((s) => `users/${s.file}`).join(", ")}.`,
    "Update the digest so it reflects the edit, then set its hash lines to:",
    ...stale.map(({ file, actual }) => `<!-- sha256 ${file} ${actual} -->`)
  ].join("\n");
}

/** Returns the TypeScript source of the generated module for the current users/*.md. */
export function renderUserProfileSourcesModule(root = repoRoot) {
  const entries = FILES.map(([key, file]) => {
    const text = readFileSync(join(root, "users", file), "utf8");
    return `  /** users/${file} */\n  ${key}: ${JSON.stringify(text)}`;
  });
  const { body: digest } = readDigest(root);
  return [
    "// GENERATED by scripts/generate-user-profile-sources.mjs from users/*.md. Do not edit.",
    "// Regenerate with `npm run generate:user-profile` after editing users/*.md.",
    'import type { UserProfileSources } from "./user-profile.types.js";',
    "",
    "/** users/*.md as committed, embedded so the functions bundle never reads files. */",
    "export const USER_PROFILE_SOURCES: UserProfileSources = {",
    entries.join(",\n"),
    "};",
    "",
    "/**",
    " * user-profile.digest.md without its comment header: the hand-written, reviewed",
    " * condensation of users/*.md that the system prompt carries.",
    " */",
    `export const USER_PROFILE_DIGEST: string = ${JSON.stringify(digest)};`,
    ""
  ].join("\n");
}

function readOrEmpty(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

/**
 * Rewrites the generated module when it differs from users/*.md.
 * Returns true when the file was (or, with check=true, would be) changed.
 */
export function syncUserProfileSourcesModule({ check = false } = {}) {
  const next = renderUserProfileSourcesModule();
  const stale = readOrEmpty(USER_PROFILE_GENERATED_PATH) !== next;
  if (stale && !check) writeFileSync(USER_PROFILE_GENERATED_PATH, next);
  return stale;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes("--check");
  const stale = syncUserProfileSourcesModule({ check });
  if (check && stale) {
    console.error("user-profile.generated.ts is out of date with users/*.md; run `npm run generate:user-profile`.");
    process.exit(1);
  }
  console.log(stale ? "user-profile.generated.ts updated from users/*.md." : "user-profile.generated.ts is up to date.");
  const staleDigest = staleUserProfileDigestSources();
  if (staleDigest.length > 0) {
    console.error(describeStaleUserProfileDigest(staleDigest));
    process.exit(1);
  }
}
