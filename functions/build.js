// Bundles the Cloud Functions entry (functions/index.js) together with the
// shared TypeScript modules it imports from ../src into functions/lib/index.js,
// which is what package.json "main" points Firebase at.
//
//   npm run build --prefix functions
//
// npm dependencies stay external (installed by Cloud Build from
// functions/package.json); only first-party code from index.js and src/ is
// inlined. After bundling, the build fails if:
//   - the bundle no longer exports `api` and `alfredCallable`, or
//   - it imports a package that is not a dependency in functions/package.json
//     (a src/ module pulling in a root-only dependency would otherwise build
//     fine here and crash on cold start in production).
import { build } from "esbuild";
import { readFileSync } from "node:fs";
import { builtinModules } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const REQUIRED_EXPORTS = ["api", "alfredCallable"];

const pkg = JSON.parse(readFileSync(join(here, "package.json"), "utf8"));
const allowedPackages = new Set(Object.keys(pkg.dependencies || {}));
const builtins = new Set(builtinModules);

function packageName(specifier) {
  if (specifier.startsWith("node:")) return null;
  const parts = specifier.split("/");
  const name = specifier.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
  return builtins.has(name) ? null : name;
}

const outfile = join(here, "lib", "index.js");

const result = await build({
  absWorkingDir: here,
  entryPoints: [join(here, "index.js")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  packages: "external",
  // src/ has its own tsconfig; point esbuild at it so TS settings match tsc.
  tsconfig: join(here, "..", "tsconfig.json"),
  legalComments: "none",
  metafile: true,
  logLevel: "warning",
  banner: {
    js: "// GENERATED by functions/build.js from functions/index.js + src/. Do not edit.",
  },
});

const problems = [];
const output = result.metafile.outputs[join("lib", "index.js")];
if (!output) {
  problems.push(`esbuild did not report lib/index.js (got: ${Object.keys(result.metafile.outputs).join(", ")})`);
} else {
  for (const name of REQUIRED_EXPORTS) {
    if (!output.exports.includes(name)) problems.push(`bundle is missing export "${name}"`);
  }
  for (const imp of output.imports) {
    if (!imp.external) continue;
    const name = packageName(imp.path);
    if (name && !allowedPackages.has(name)) {
      problems.push(`bundle imports "${imp.path}", but "${name}" is not in functions/package.json dependencies`);
    }
  }
}

if (problems.length > 0) {
  console.error("functions build failed checks:\n  - " + problems.join("\n  - "));
  process.exit(1);
}

const bundled = Object.keys(output.inputs).sort();
console.log(`functions/lib/index.js built: exports [${output.exports.join(", ")}], ${bundled.length} inputs:`);
for (const input of bundled) console.log(`  ${input}`);
